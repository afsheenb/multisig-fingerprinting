"""Anonymous provider *candidate* discovery from exported on-chain key/script graph.

No network access and no third-party dependencies. This intentionally never
assigns a legal entity. A script shared-key cohort is an exact key link; a
structural family is only a same-implementation hypothesis.

Usage: python -m msfp cohorts --graph-dir reports/graph --out-dir reports/cohorts
The command also works from an exported graph without the SQLite corpus.
"""
import collections
import csv
import hashlib
import json
from pathlib import Path
import math


def _read_csv(path):
    with open(path, newline='', encoding='utf-8') as f:
        yield from csv.DictReader(f)


def _int(value):
    return int(value) if value not in ('', None) else None


def _is_real_pubkey(pk):
    if not isinstance(pk, str) or len(pk) not in (66, 130):
        return False
    if not (len(pk) == 66 and pk[:2] in ('02','03') or
            len(pk) == 130 and pk[:2] == '04'):
        return False
    try:
        bytes.fromhex(pk)
    except ValueError:
        return False
    return True


def _compact_numbers(counter):
    return dict(sorted(counter.items(), key=lambda kv: str(kv[0])))


def analyze(graph_dir, min_shared=5):
    """Report exact ECDSA CHECKMULTISIG key hubs and anonymous structural groups.

    `nodes_script.csv` and `edges_key_in_script.csv` are generated by the
    repository's `msfp attribute` step. We do not use the ambiguous provider
    labels, and reject Taproot/tapscript pushes from the key index to avoid
    treating inscription payloads as cryptographic custody keys.
    """
    graph_dir = Path(graph_dir)
    scripts = {}
    morph = collections.Counter()
    for row in _read_csv(graph_dir / 'nodes_script.csv'):
        if (row['family_l4'] != 'standard_multisig' or
            row['script_class'] != 'multisig' or
            row['source'] not in ('p2sh_redeem','p2wsh_witness','p2sh_p2wsh_witness')):
            continue
        threshold = _int(row['threshold'])
        nkeys = _int(row['n_keys'])
        if threshold is None or nkeys is None or not (1 <= threshold <= nkeys <= 20):
            continue
        sha = row['script_sha256']
        scripts[sha] = {'id': sha, 'threshold':threshold, 'n_keys':nkeys,
            'template':row['template_l3'], 'source':row['source'],
            'keys_sorted': _int(row['keys_sorted']),
            'first_height':_int(row['first_seen_height']),
            'last_height':_int(row['last_seen_height']),
            'observations':_int(row['n_observations']) or 0,
            'keys':[], 'key_positions':{}}
        morph[(row['source'],threshold,nkeys,row['keys_sorted'],row['template_l3'])] += 1

    key_members = collections.defaultdict(set)
    malformed = collections.Counter()
    for row in _read_csv(graph_dir / 'edges_key_in_script.csv'):
        sha = row['script_sha256']
        if sha not in scripts:
            continue
        pk = row['pubkey_hex']
        if not _is_real_pubkey(pk):
            malformed['malformed_or_non_ecdsa'] += 1
            continue
        pos = _int(row['position'])
        if pos is None:
            malformed['missing_position'] += 1
            continue
        sc = scripts[sha]
        if pk in sc['key_positions']:
            malformed['duplicate_key_position'] += 1
            continue
        sc['keys'].append(pk)
        sc['key_positions'][pk] = pos
        key_members[pk].add(sha)

    # Only consider scripts with the full advertised complement of keys.
    valid = {sha: s for sha,s in scripts.items() if len(s['keys']) == s['n_keys']}
    missing = len(scripts) - len(valid)
    key_members = collections.defaultdict(set)
    for sha, s in valid.items():
        for pk in s['keys']:
            key_members[pk].add(sha)

    family_members = collections.defaultdict(set)
    for sha, sc in valid.items():
        family_members[(sc['threshold'], sc['n_keys'])].add(sha)

    morph_rows = []
    for shape, count in morph.most_common():
        source, threshold,nkeys,sort,templ=shape
        morph_rows.append(dict(source=source, threshold=threshold, n_keys=nkeys,
                               keys_sorted=None if sort == '' else int(sort),
                               template=templ, n_scripts=count))

    anchors = []
    for shape, scs in sorted(family_members.items()):
        k,n = shape
        # Scope key anchors to quorum. Same public key across different script
        # structures is reported as multiple distinct observations.
        scoped_members = collections.defaultdict(set)
        for sha in scs:
            for pk in valid[sha]['keys']:
                scoped_members[pk].add(sha)
        repeat = {pk: members for pk, members in scoped_members.items()
                  if len(members) >= min_shared}
        # Construct connected groups of keys whose observed sets *nearly
        # coincide*. This collapses the 3 recurring keys in the same 3-of-4
        # arrangement but NEVER merges through mere co-occurrence in 1 script.
        parent = {pk:pk for pk in repeat}
        def find(pk):
            while parent[pk] != pk:
                parent[pk] = parent[parent[pk]]
                pk = parent[pk]
            return pk
        def union(a,b):
            a,b = find(a),find(b)
            if a != b:
                parent[max(a,b)] = min(a,b)
        for sha in scs:
            pks = [pk for pk in valid[sha]['keys'] if pk in repeat]
            for i,pk1 in enumerate(pks):
                for pk2 in pks[i+1:]:
                    a,b=repeat[pk1],repeat[pk2]
                    if len(a & b) >= min_shared and len(a&b)/max(len(a),len(b)) >= 0.9:
                        union(pk1,pk2)
        groups = collections.defaultdict(list)
        for pk in repeat:
            groups[find(pk)].append(pk)
        for component in groups.values():
            # report each cohort via its union of distinct scripts
            members = set().union(*(repeat[pk] for pk in component))
            if not members:
                continue
            main_key = sorted(component, key=lambda p: (-len(repeat[p]),p))[0]
            common = set.intersection(*(repeat[pk] for pk in component))
            sources=collections.Counter(valid[sha]['source'] for sha in members)
            sortedness=collections.Counter('sorted' if valid[sha]['keys_sorted']==1
                                          else 'unsorted' if valid[sha]['keys_sorted']==0
                                          else 'unknown' for sha in members)
            positions={pk:dict(sorted(collections.Counter(valid[sha]['key_positions'][pk]
                       for sha in repeat[pk]).items())) for pk in component}
            spans=[valid[sha]['first_height'] for sha in members if valid[sha]['first_height'] is not None]
            last=[valid[sha]['last_height'] for sha in members if valid[sha]['last_height'] is not None]
            distinct_cosets={tuple(sorted(valid[sha]['keys'])) for sha in members}
            first_height_counts=collections.Counter(valid[sha]['first_height'] for sha in members)
            digest=hashlib.sha256(f'{k}/{n}:'.encode()+main_key.encode()).hexdigest()[:12]
            anchors.append({'cohort_id':f'cohort_{digest}', 'threshold':k, 'n_keys':n,
                'anchor_key':main_key, 'co_recurring_keys':sorted(component),
                'n_distinct_scripts':len(members), 'n_jointly_shared_scripts':len(common),
                'n_distinct_cosigner_sets':len(distinct_cosets),
                'sources':_compact_numbers(sources), 'sorting':_compact_numbers(sortedness),
                'anchor_positions':positions[main_key],
                'all_repeated_key_positions': positions,
                'first_height':min(spans) if spans else None,
                'last_height':max(last) if last else None,
                'n_distinct_first_seen_heights':len(first_height_counts),
                'largest_same_height_batch':max(first_height_counts.values()) if first_height_counts else 0,
                'example_scripts':sorted(members)[:3],
                # Expose script ids to support reproducible member exports, but
                # avoid keeping 2,000 ids in the human-readable summary.
                '_members': members})

    anchors.sort(key=lambda a:(-a['n_distinct_scripts'],-len(a['co_recurring_keys']),a['cohort_id']))
    # Overlap-aware unique coverage across repeated-key cohorts per quorum.
    cover=collections.defaultdict(set)
    for a in anchors:
        cover[(a['threshold'],a['n_keys'])].update(a['_members'])
    coverage=[{'threshold':k,'n_keys':n,'n_scripts':len(v),
         'n_scripts_in_hub_cohorts':len(cover.get((k,n),set())),
         'fraction_hub_linked':round(len(cover.get((k,n),set()))/len(v),6)}
         for (k,n),v in sorted(family_members.items())]
    # Distinct structure groups are useful architecture *fingerprints* but NOT
    # provider identifiers. We explicitly avoid ungrounded firm labels.
    exact_num_2of3 = {sha: s for sha,s in valid.items() if s['threshold']==2 and s['n_keys']==3 and s['source']=='p2wsh_witness'}
    n2=len(exact_num_2of3)
    obs2=sum(s['keys_sorted']==1 for s in exact_num_2of3.values())
    chance=1/math.factorial(3)
    p = (obs2/n2-chance)/(1-chance) if n2 else None
    mixture={'model':'two-component (always BIP67 sorted versus uniformly randomly ordered; exploratory only)',
             'population':'native/segwit P2WSH revealed 2-of-3 scripts; distinct scripts',
             'n_scripts':n2,'n_sorted':obs2,
             'observed_sorted_fraction':round(obs2/n2,6) if n2 else None,
             'estimated_deliberate_sorted_fraction':round(max(0,min(1,p)),6) if p is not None else None,
             'caveat':'This is NOT a provider count. Independence, uniform permutation, and representative sampling are unverified. Do not attribute individual sorted scripts.'}
    members_csv=[]
    for a in anchors:
        for sha in sorted(a.pop('_members')):
            members_csv.append({'cohort_id':a['cohort_id'],'script_sha256':sha})
    out={'method':'anonymous shared-key cohorts; exact ECDSA pubkeys, quorum scope, >=%d distinct scripts per anchor'%min_shared,
         'graph_dir':str(graph_dir),'n_standard_multisig_scripts':len(valid),
         'n_excluded_incomplete_scripts':missing,
         'n_unique_pubkeys':len(key_members),
         'n_anonymous_key_cohorts':len(anchors),
         'n_structural_groups':len(morph_rows),
         'counts_by_quorum':coverage,
         'sorted_2of3_mixture':mixture,
         'key_cohorts':anchors,'structural_groups':morph_rows,
         'notes':['Shared exact keys provide a deterministic script link, not a company identity.',
                  'Same script structures and BIP67 orderings do not establish an operator.',
                  'Known script IDs appear only when spent in sampled blocks; rates are not chain-wide estimates.',
                  'Signature-role assignments require validated signed transactions and are unavailable in exported graph.',
                  'No new Blockchair or mempool.space requests are performed.']}
    return out, members_csv


def write_outputs(data, members, out_dir):
    out_dir=Path(out_dir)
    out_dir.mkdir(parents=True,exist_ok=True)
    (out_dir/'anonymous_cohorts.json').write_text(json.dumps(data,indent=2)+'\n',encoding='utf-8')
    with (out_dir/'cohort_script_members.csv').open('w',newline='',encoding='utf-8') as f:
        w=csv.DictWriter(f,fieldnames=['cohort_id','script_sha256'])
        w.writeheader()
        w.writerows(members)
    lines=['# Anonymous multisig implementation cohorts','',
           'Offline analysis of exported on-chain script and public-key data. **No company is identified by this report.**','',
           f"Standard CHECKMULTISIG scripts: **{data['n_standard_multisig_scripts']:,}**. Distinct anonymous repeated-key cohorts (minimum 5 separate scripts): **{data['n_anonymous_key_cohorts']:,}**.",'',
           '## Shared-key coverage by quorum','',
           '| Quorum | Scripts | Linked to reused key (≥5 scripts) | Share |','|---|---:|---:|---:|']
    for row in data['counts_by_quorum']:
        if row['n_scripts'] >= 20:
            lines.append(f"| {row['threshold']}/{row['n_keys']} | {row['n_scripts']:,} | {row['n_scripts_in_hub_cohorts']:,} | {100*row['fraction_hub_linked']:.2f}% |")
    lines += ['', '## Largest exact-key cohorts','',
              '| Cohort | Quorum | Unique scripts | Distinct first-seen blocks | Repeated keys | Ordering | Main key position(s) |',
              '|---|---:|---:|---:|---:|---|---|']
    for a in data['key_cohorts'][:25]:
        sort=', '.join(f'{s}={n}' for s,n in a['sorting'].items())
        pos=', '.join(f'{p}={n}' for p,n in a['anchor_positions'].items())
        lines.append(f"| `{a['cohort_id']}` | {a['threshold']}/{a['n_keys']} | {a['n_distinct_scripts']:,} | {a['n_distinct_first_seen_heights']:,} | {len(a['co_recurring_keys'])} | {sort} | {pos} |")
    m=data['sorted_2of3_mixture']
    lines += ['', '**Single-block caveat:** a cohort whose scripts first appear in just one sampled block may be one batch transaction rather than evidence of a persistent service. Compare cohort IDs and scripts against transaction IDs before inferring ongoing operation.', '', '## Exploratory mixture for ordinary P2WSH 2-of-3','',
              f"{m['n_sorted']:,} of {m['n_scripts']:,} distinct scripts are lexicographically sorted ({100*m['observed_sorted_fraction']:.2f}%).",
              f"Under a simplified always-sorted vs randomly-ordered model, the implied deliberately-sorted share is **{100*m['estimated_deliberate_sorted_fraction']:.2f}%**.",'',
              '**Not a provider estimate.** Assumptions and selection effects may invalidate the mixture.','',
              '## Interpretation and next validation','',
              'An identical pubkey across distinct scripts is proof of a common script key, but not of company control. Role-based sorting, different thresholds, script forms, and key-reuse shape create anonymous implementation families. They are not automatically one-provider-per-family.', '',
              'To attach provider names or identify signing roles, recover independently authenticated wallet descriptors/transactions and join full verified signing positions from the local corpus SQLite database. That SQLite corpus is not required for this offline analysis.', '',
              'All script memberships are exported in `cohort_script_members.csv`. No blockchain API was called.', '']
    (out_dir/'anonymous_cohorts.md').write_text('\n'.join(lines),encoding='utf-8')
    return out_dir


def main(argv=None):
    import argparse
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--graph-dir',default='reports/graph')
    p.add_argument('--out-dir',default='reports/cohorts')
    p.add_argument('--min-shared',type=int,default=5)
    args=p.parse_args(argv)
    if args.min_shared < 2:
        p.error('--min-shared must be >= 2')
    data,members=analyze(args.graph_dir,args.min_shared)
    write_outputs(data,members,args.out_dir)
    print(f"{data['n_standard_multisig_scripts']:,} standard multisig scripts; "
          f"{data['n_anonymous_key_cohorts']} anonymous shared-key cohorts; "
          f"report: {args.out_dir}/anonymous_cohorts.md")
    return data


if __name__=='__main__':
    main()
